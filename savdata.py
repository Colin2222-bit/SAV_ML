vims_df = pd.read_excel(file_path, sheet_name='VIMS_Data', skiprows=1) # Update sheet name if different

# ---------------------------------------------------------
# PART A: PROCESS VIMS WIDEWATER QUADRANGLE (2022–2026)
# ---------------------------------------------------------
# Filter for QuadID 55 (Widewater; Va.- Md.)
vims_widewater = vims_df[vims_df['Quadid'] == 55]

# Extract columns matching 2022 to 2026 hectare values
# VIMS columns typically look like '2022_ha', '2023_ha', etc.
years = [2022, 2023, 2024, 2025, 2026]
vims_hectares = []

for yr in years:
    col_name = f'{yr}_ha'
    if col_name in vims_widewater.columns:
        val = vims_widewater[col_name].values[0]
        # Handle non-numeric text like 'nd' (not detected/mapped) safely
        val = pd.to_numeric(val, errors='coerce')
        vims_hectares.append(val)
    else:
        vims_hectares.append(float('nan'))

vims_summary = pd.DataFrame({'Year': years, 'VIMS_Hectares': vims_hectares})

# ---------------------------------------------------------
# PART B: PROCESS & COMBINE NOAA + COMMUNITY SURVEYS
# ---------------------------------------------------------
# Standardize year and cover columns for NOAA data
sav['Date'] = pd.to_datetime(sav['Date'], errors='coerce')
sav['Year'] = sav['Date'].dt.year
# If your NOAA sheet uses 'Total SAV' instead of '% Cover', map it safely:
if 'Total SAV % Cover' not in sav.columns and 'Total SAV' in sav.columns:
    sav['Total SAV % Cover'] = sav['Total SAV']

# Select relevant columns from both datasets
noaa_subset = sav[['Year', 'Total SAV % Cover']].copy()
comm_subset = savcommunity[['Year', 'Total SAV % Cover']].copy()

# Combine both survey dataframes into one
combined_surveys = pd.concat([noaa_subset, comm_subset], ignore_index=True)

# Clean and calculate the annual average % cover
combined_surveys['Total SAV % Cover'] = pd.to_numeric(combined_surveys['Total SAV % Cover'], errors='coerce')
survey_avg = combined_surveys.groupby('Year')['Total SAV % Cover'].mean().reset_index()
survey_avg.rename(columns={'Total SAV % Cover': 'Avg_Survey_Cover'}, inplace=True)

# Merge VIMS summary with Combined Survey averages by Year
comparison_df = pd.merge(vims_summary, survey_avg, on='Year', how='inner')
print("--- Annual Comparison Data ---")
