def datacleaningandmapping(df):
# 3. Clean the GPS coordinates
  df['Latitude'] = pd.to_numeric(df['Latitude'], errors='coerce')
  df['Longitude'] = pd.to_numeric(df['Longitude'], errors='coerce')

  # Drop missing coordinates
  df = df.dropna(subset=['Latitude', 'Longitude'])

  # NEW: Filter for realistic Maryland coordinates to prevent global outliers
  df = df[(df['Latitude'] > 38.0) & (df['Latitude'] < 39.0)]
  df = df[(df['Longitude'] > -78.0) & (df['Longitude'] < -76.0)]

  # ... (Keep your imports and data cleaning exactly the same) ...

  # NEW: Explicitly set the map boundaries based on your data + a tiny margin
  margin = 0.01
  min_lon, max_lon = df['Longitude'].min() - margin, df['Longitude'].max() + margin
  min_lat, max_lat = df['Latitude'].min() - margin, df['Latitude'].max() + margin

  vmin_val = 0
  vmax_val = 4
  request = cimgt.OSM()
  return df, min_lon, max_lon, min_lat, max_lat, request, vmin_val, vmax_val

sav, min_lon, max_lon, min_lat, max_lat, request, vmin_val, vmax_val = datacleaningandmapping(sav)
# Loop 1: Go through each unique Year
for year in sav['Date'].dt.year.dropna().unique():

    # Filter the data to just this specific year
    sav_year = sav[sav['Date'].dt.year == year]

    # Create the figure and 2x3 grid OUTSIDE the date loop
    # FIX: We must pass the Cartopy projection here using subplot_kw!
    fig, axes = plt.subplots(nrows=3, ncols=4, figsize=(15, 8),
                             subplot_kw={'projection': ccrs.PlateCarree()})

    # FIX: Flatten the 2x3 grid into a 1D list so we can easily loop through it as axes[0], axes[1], etc.
    axes = axes.flatten()

    # Get unique dates for this specific year
    unique_dates = sav_year['Date'].unique()

    # Loop 2: Go through the dates and plot them on the axes
    # enumerate() automatically gives us an index 'i' (0, 1, 2...) and the 'date'
    for i, date in enumerate(unique_dates):

        # Safety check: if there are more than 6 dates in a year, stop at 6 so we don't crash


        sav_date = sav_year[sav_year['Date'] == date]

        # Grab the specific subplot axis for this date
        ax = axes[i]

        ax.set_extent([min_lon, max_lon, min_lat, max_lat], crs=ccrs.PlateCarree())
        ax.add_image(request, 12)

        scatter = ax.scatter(
            sav_date['Longitude'],
            sav_date['Latitude'],
            c=sav_date['Total SAV'],
            cmap='viridis',
            vmin=vmin_val,
            vmax=vmax_val,
            s=14,
            edgecolor='black',
            linewidth=0.5,
            transform=ccrs.PlateCarree()
        )

        # Clean up the date format for the subplot title
        clean_date = pd.to_datetime(date).strftime("%Y-%m-%d")
        ax.set_title(f'{clean_date}')

    # FIX: If a year has FEWER than 6 dates, this hides the empty, unused subplots
    for j in range(i + 1, 12):
        fig.delaxes(axes[j])

    # FIX: Add a single colorbar to the side of the entire figure, not per-subplot
    cbar = fig.colorbar(scatter, ax=axes, orientation='vertical', fraction=0.02, pad=0.04)
    cbar.set_label('Total SAV % Cover')

    # Add a main title for the whole 6-panel figure
    fig.suptitle(f'Mallows Bay SAV Coverage - {int(year)}', fontsize=16)

    plt.show()

